(function () {
  const lang = document.documentElement.lang || 'ru';

  const strings = {
    ru: {
      searchEmpty: 'Ничего не найдено. Попробуйте другое слово.',
      scoreTitle: score => `Ваш результат: ${score} из 21 балла`,
      levels: [
        'Вы не отметили эпизодов недержания мочи.',
        'Лёгкая степень (1–5 баллов).',
        'Умеренная степень (6–12 баллов).',
        'Тяжёлая степень (13–18 баллов).',
        'Очень тяжёлая степень (19–21 балл).'
      ],
      adviceNone: 'Если у вас есть другие беспокоящие симптомы со стороны мочевого пузыря, обсудите их с врачом.',
      advice: 'Результат не является диагнозом. Покажите его врачу — он поможет выбрать обследование и лечение. Помощь доступна при любой степени выраженности.',
      situations: 'Когда происходит подтекание',
      print: 'Распечатать или сохранить в PDF',
      date: 'Дата заполнения'
    },
    kk: {
      searchEmpty: 'Ештеңе табылмады. Басқа сөзбен іздеп көріңіз.',
      scoreTitle: score => `Сіздің нәтижеңіз: 21 ұпайдан ${score}`,
      levels: [
        'Сіз зәр ұстамау эпизодтарын белгілемедіңіз.',
        'Жеңіл дәреже (1–5 ұпай).',
        'Орташа дәреже (6–12 ұпай).',
        'Ауыр дәреже (13–18 ұпай).',
        'Өте ауыр дәреже (19–21 ұпай).'
      ],
      adviceNone: 'Қуықпен байланысты басқа мазалайтын белгілер болса, оларды дәрігермен талқылаңыз.',
      advice: 'Нәтиже диагноз емес. Оны дәрігерге көрсетіңіз — ол тексеру мен емді таңдауға көмектеседі. Көмек кез келген дәрежеде қолжетімді.',
      situations: 'Зәр қашан ағады',
      print: 'Басып шығару немесе PDF ретінде сақтау',
      date: 'Толтырылған күні'
    },
    en: {
      searchEmpty: 'Nothing found. Try another word.',
      scoreTitle: score => `Your score: ${score} out of 21`,
      levels: [
        'You did not report any leakage.',
        'Slight (1–5 points).',
        'Moderate (6–12 points).',
        'Severe (13–18 points).',
        'Very severe (19–21 points).'
      ],
      adviceNone: 'If you have other bladder symptoms that bother you, discuss them with a doctor.',
      advice: 'This result is not a diagnosis. Show it to your doctor, who can help choose tests and treatment. Help is available at any level of severity.',
      situations: 'When urine leaks',
      print: 'Print or save as PDF',
      date: 'Date completed'
    }
  };
  const t = strings[lang] || strings.ru;

  const escapeHtml = value => String(value).replace(/[&<>"']/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[ch]));

  // Site search over the index generated by build.py.
  const results = document.querySelector('.search-results');
  document.querySelectorAll('.site-search').forEach(form => {
    const input = form.querySelector('input');
    form.addEventListener('submit', event => {
      event.preventDefault();
      if (!results) return;
      const query = input.value.trim().toLowerCase();
      if (!query) {
        results.classList.remove('visible');
        results.innerHTML = '';
        return;
      }
      const words = query.split(/\s+/);
      const pages = (window.UW_SEARCH && window.UW_SEARCH[lang]) || [];
      const matches = pages
        .map(page => {
          const title = page.t.toLowerCase();
          const text = `${title} ${page.d} ${page.x}`.toLowerCase();
          if (!words.every(word => text.includes(word))) return null;
          const score = words.reduce((sum, word) => sum + (title.includes(word) ? 10 : 0) + text.split(word).length, 0);
          return { page, score };
        })
        .filter(Boolean)
        .sort((a, b) => b.score - a.score)
        .slice(0, 8);
      results.innerHTML = matches.length
        ? matches.map(({ page }) => `<a href="${escapeHtml(page.u)}"><strong>${escapeHtml(page.t)}</strong><span>${escapeHtml(page.d)}</span></a>`).join('')
        : `<p>${escapeHtml(t.searchEmpty)}</p>`;
      results.classList.add('visible');
    });
  });
  document.addEventListener('keydown', event => {
    if (event.key === 'Escape' && results) results.classList.remove('visible');
  });

  // ICIQ-SF: score = frequency (0–5) + amount (0, 2, 4, 6) + impact (0–10).
  // Severity bands after Klovning et al., Neurourol Urodyn 2009.
  const iciqForm = document.getElementById('iciq-form');
  const iciqResult = document.getElementById('iciq-result');
  if (iciqForm && iciqResult) {
    const impact = iciqForm.querySelector('input[name="impact"]');
    const impactValue = document.getElementById('impact-value');
    if (impact && impactValue) {
      const sync = () => { impactValue.textContent = impact.value; };
      impact.addEventListener('input', sync);
      sync();
    }

    iciqForm.addEventListener('submit', event => {
      event.preventDefault();
      const data = new FormData(iciqForm);
      const score = Number(data.get('frequency')) + Number(data.get('amount')) + Number(data.get('impact'));
      const band = score === 0 ? 0 : score <= 5 ? 1 : score <= 12 ? 2 : score <= 18 ? 3 : 4;
      const situations = data.getAll('situation');
      const situationList = situations.length
        ? `<p><strong>${escapeHtml(t.situations)}:</strong> ${situations.map(escapeHtml).join('; ')}</p>`
        : '';
      // Browsers often lack kk-KZ date data, so Kazakh uses the same dd.mm.yyyy format as Russian.
      const today = new Date().toLocaleDateString(lang === 'en' ? 'en-GB' : 'ru-RU');

      iciqResult.innerHTML =
        `<h3>${escapeHtml(t.scoreTitle(score))}</h3>` +
        `<p><strong>${escapeHtml(t.levels[band])}</strong></p>` +
        situationList +
        `<p>${escapeHtml(band === 0 ? t.adviceNone : t.advice)}</p>` +
        `<p class="small-note">${escapeHtml(t.date)}: ${escapeHtml(today)}</p>` +
        `<button type="button" class="button button-secondary no-print" data-print>${escapeHtml(t.print)}</button>`;
      iciqResult.classList.add('visible');
      iciqResult.querySelector('[data-print]').addEventListener('click', () => window.print());
      iciqResult.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
      iciqResult.focus({ preventScroll: true });
    });

    iciqForm.addEventListener('reset', () => {
      iciqResult.classList.remove('visible');
      iciqResult.innerHTML = '';
      if (impactValue) setTimeout(() => { impactValue.textContent = impact.value; });
    });
  }
})();
